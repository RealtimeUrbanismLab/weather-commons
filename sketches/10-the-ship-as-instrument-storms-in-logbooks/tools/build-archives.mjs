#!/usr/bin/env node
// Which archives hold the logbooks behind the map: entries (one per logbook per day, as on the map) and logbooks per archive.
//   node tools/build-archives.mjs path/to/cliwoc21.gpkg   → data/archives.js
import { DatabaseSync } from 'node:sqlite';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const db = new DatabaseSync(process.argv[2], { readOnly: true });
const rows = db.prepare(`SELECT InstName i, InstPlace p, InstLand l, LogbookIdent g, Year y, Month m, Day d
  FROM CLIWOC21 WHERE Year IS NOT NULL AND Month BETWEEN 1 AND 12 AND Day BETWEEN 1 AND 31 AND latitude IS NOT NULL AND longitude IS NOT NULL`).all();
const title = s => String(s || '').toLowerCase().replace(/(^|[\s'(-])\S/g, c => c.toUpperCase());
// fuller or English-friendly names where CLIWOC's are abbreviated or duplicated
const NAME = {
  "CENTRE D'ACCUEIL ET DE RECHERCHE DES ARCH. NATION.": 'Archives nationales (CARAN)',
  'ARCHIVO MUSEO NAVAL MADRID': 'Archivo del Museo Naval Madrid',
  'NEDERLANDS INSTITUUT VOOR WETENSCHAPPELIJKE INFORM': 'Nederlands Instituut voor Wetenschappelijke Informatiediensten',
  'KONINKLIJK NEDERLANDS METEOROLOGISCH INSTITUUT': 'Koninklijk Nederlands Meteorologisch Instituut (KNMI)',
  'RIJKSARCHIEF ZEELAND': 'Rijksarchief Zeeland (now Zeeuws Archief)',
  'PUBLIC RECORD OFFICE': 'Public Record Office (now The National Archives)',
};
const COUNTRY = { NEDERLAND: 'Netherlands', 'UNITED KINGDOM': 'United Kingdom', SPAIN: 'Spain', FRANCE: 'France', SWEDEN: 'Sweden' };
const seen = new Set(), A = new Map();
for (const r of rows) {
  const k = r.g + '|' + r.y + '-' + r.m + '-' + r.d; if (seen.has(k)) continue; seen.add(k);
  const name = NAME[r.i] || (r.i ? title(r.i) : 'Archive not recorded'), key = name + '|' + r.l;
  if (!A.has(key)) A.set(key, { name, place: title(r.p), country: COUNTRY[r.l] || title(r.l), n: 0, logs: new Set(), y0: 9999, y1: 0 });
  const a = A.get(key); a.n++; a.logs.add(r.g); a.y0 = Math.min(a.y0, r.y); a.y1 = Math.max(a.y1, r.y);
}
const total = seen.size;
const list = [...A.values()].map(a => ({ name: a.name, place: a.place, country: a.country, entries: a.n, logbooks: a.logs.size, from: a.y0, to: a.y1 }))
  .sort((a, b) => b.entries - a.entries);
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'data', 'archives.js');
fs.writeFileSync(out, `// Generated by tools/build-archives.mjs from CLIWOC 2.1 (CC0, https://doi.org/10.17026/dans-2bx-dutg).\n` +
  `// The archives holding the logbooks behind the map: noon entries (one per logbook per day) and logbooks in each.\n` +
  `window.ARCHIVES = ${JSON.stringify({ total, list })};\n`);
console.log(list.length, 'archives,', total, 'entries');
