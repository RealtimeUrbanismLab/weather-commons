#!/usr/bin/env node
// Turn tools/events-source.json (hand-checked imperial events matched to CLIWOC ships) into data/events.js.
//   node tools/build-events.mjs   (run after build-data.mjs, which writes data/ships.js)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const src = JSON.parse(fs.readFileSync(path.join(here, 'events-source.json'), 'utf8'));
globalThis.window = {};
new Function('window', fs.readFileSync(path.join(here, '..', 'data', 'ships.js'), 'utf8'))(globalThis.window);
const SHIPS = window.CLIWOC_SHIPS;
const EPOCH = Date.UTC(1662, 0, 1);
const day = (s) => Math.round((Date.parse(s + 'T00:00:00Z') - EPOCH) / 864e5);
const missing = [];
const events = src.map((e) => {
  const [a, b] = e.date.split('/');
  const ships = [];
  for (const s of e.ships) {
    const i = SHIPS.findIndex((x) => x.name === s.ship && x.natName === s.nat);
    if (i < 0) missing.push(`${s.ship} (${s.nat}) in ${e.name}`); else if (!ships.includes(i)) ships.push(i);
  }
  return { name: e.name, start: day(a), end: day(b || a), lat: e.lat, lon: e.lon, radiusKm: e.radius_km, type: e.type,
    ships, evidence: e.evidence, sources: e.sources || [], confidence: e.confidence };
});
fs.writeFileSync(path.join(here, '..', 'data', 'events.js'),
  `// Generated by tools/build-events.mjs from tools/events-source.json: imperial and colonial events that CLIWOC ships took part in.\n` +
  `// Matched on ship name, date and position, with the logbooks' own remarks as evidence. Days since 1662-01-01.\n` +
  `window.EVENTS = ${JSON.stringify(events)};\n`);
console.log(events.length, 'events;', missing.length ? 'unmatched ships: ' + missing.join('; ') : 'all ships matched');
