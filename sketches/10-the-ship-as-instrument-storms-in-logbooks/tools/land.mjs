#!/usr/bin/env node
// World coastlines for the map from Natural Earth 1:50m land (public domain), written to data/land.js.
//   node tools/land.mjs
// Source: https://github.com/nvkelso/natural-earth-vector (v5.1.2, geojson/ne_50m_land.geojson), read over the network.
// Keeps every outer ring, rounded to 0.1 degree, with repeated points dropped.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const URL = 'https://raw.githubusercontent.com/nvkelso/natural-earth-vector/v5.1.2/geojson/ne_50m_land.geojson';
const out = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'data', 'land.js');
const geo = await (await fetch(URL)).json();
const rings = [];
for (const f of geo.features) {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) {
    const pts = [];
    for (const [x, y] of poly[0]) { const p = [Math.round(x * 10) / 10, Math.round(y * 10) / 10], l = pts[pts.length - 1]; if (!l || l[0] !== p[0] || l[1] !== p[1]) pts.push(p); }
    if (pts.length > 3) rings.push(pts);
  }
}
fs.writeFileSync(out, `// Generated by tools/land.mjs from Natural Earth 1:50m land (public domain), whole world.\nwindow.LAND = ${JSON.stringify(rings)};\n`);
console.log(`Wrote ${rings.length} land outlines, ${(fs.statSync(out).size / 1e6).toFixed(2)} MB`);
